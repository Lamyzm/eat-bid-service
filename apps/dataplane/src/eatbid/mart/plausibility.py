"""모듈 책임: 문법은 통과하지만 업무적으로 불가능한 회차 값을 mart가 격리하는 규칙과 그 근거를 한 곳에 둔다.

회차 요약과 열린 공고 스냅샷이 같은 상한을 쓰지 않으면 한 회차가 한쪽에서는 격리되고 다른 쪽에서는 유령으로
남는다(EAT-199).
"""

from __future__ import annotations

from decimal import Decimal

# 공고 뒤 개찰까지의 상한(일). 2026-09-17 복원본 전수 152,639회차에서 낙찰이 있는 128,582회차의 최대 간격은
# 24.3일이고, 45일을 넘는 회차는 5건뿐이며 전부 낙찰·명단이 없다(85·111·368·1101·1104일). 다섯 건 모두 원천
# payload가 그 날짜를 그대로 준 것이라 파싱이 만든 값이 아니고, 첫 수집분(시도 id 3·4)의 흔적도 아니다 — 원천의
# 입력 오류로 본다. 상한을 낙찰 최대치의 두 배 가까이 잡아 정상 회차가 걸리지 않게 한다.
IMPLAUSIBLE_OPENING_GAP_DAYS = 45

# 회차 요약의 `quarantine_reason` 값. 표의 check가 이 값만 허용한다.
OPENING_GAP_QUARANTINE_REASON = "opening-gap-over-45-days"

# 예정가격 ÷ 기초금액이 이 구간 밖이면 두 금액은 같은 것을 센 값이 아니다. eaT는 예정가격을 기초금액 ±3% 안의 복수예비가격에서
# 뽑는다. 2026-10-16 core 최신 개정본 1,885,705회차 가운데 1,885,437회차가 ±3% 안, 42회차가 ±5% 안, 25회차가 ±25% 안,
# 3회차가 두 배 안이고, 198회차가 두 배 밖이다. 두 배 밖의 낙찰 112회차는 기초금액 수억 원에 예정가격 수천 원이라 예정가격이
# 다른 단위(단가)로 적힌 꼴이고, 낙찰 사정률은 83% 안팎으로 정상이다. 가장 먼 회차는 기초금액 430원·예정가격 3,855만 원
# (2016-03, 원천 `BGNG_PRC` 그대로)이고, 그 회차의 하한을 기초금액 축으로 옮긴 값이 투찰률 열(numeric(9,4))을 넘쳐 과거 기록
# mart 빌드 전체가 실패했다(EAT-365). 이 구간 밖에서는 기초금액 축 값을 만들지 않는다(null). 행은 격리하지 않는다 — 사정률과
# 낙찰은 예정가격 축의 관측이라 그대로 맞다. 구간을 넓게 잡아 ±25% 안팎의 드문 회차는 그대로 둔다.
COMPARABLE_PLANNED_TO_BASE_MIN = Decimal("0.5")
COMPARABLE_PLANNED_TO_BASE_MAX = Decimal(2)
