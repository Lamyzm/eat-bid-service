"""모듈 책임: eaT가 쓰는 시도 축약명과 행정안전부 정식 시도명의 사람이 승인한 대응 표 하나를 갖는다.

왜 이 표가 코드에 있어야 하나. 정부는 축약명 대조표를 파일로 주지 않는다. 그래서 이 대응은 관측이
아니라 **승인**이며(`reviewed`), 승인을 남길 자리가 없으면 지역 축은 영원히 0행이다
(`docs/operations/reference-data-coverage.md` §3). 근거는 지방자치법과 행정안전부가 공표문에 쓰는
공식 약칭이고, 17개 시도는 법 개정 없이는 늘지 않으므로 이 표는 목록이 아니라 상수다.

왜 유사도가 아니라 표인가. `서울`이 `서울특별시`의 접두사라는 사실로 이으면 `기해시`·`급식소(경상남도`
같은 오염이 같은 문으로 들어온다(PDR-0001이 실측으로 기각). 표는 열거된 17쌍 밖으로 한 글자도
넘어가지 않는다.

이 표가 여는 것은 **시도 토막 하나**뿐이다. 시군구 이름은 eaT와 행안부가 이미 같은 문자열을 쓰므로
그 시도 안에서 유일하게 일치할 때만 행이 되고 상태는 `label_verified`다(ADR 0035 결정 6).
"""

from __future__ import annotations

from collections.abc import Mapping

# 한 축약명이 값 여러 개를 갖는 것은 같은 구역을 부르는 이름이 법 개정으로 바뀌었기 때문이다.
# 강원은 2023-06-11 강원특별자치도로, 전북은 2024-01-18 전북특별자치도로 개편됐고 그 이전 release는
# 옛 이름을 싣는다. 어느 쪽이 활성인지는 우리가 고르지 않고 그 release가 말한다 — 활성 member에
# 없는 이름은 대조에서 그냥 빠진다. 한 release가 두 이름을 모두 활성으로 실으면 후보가 둘이 되어
# 행이 만들어지지 않는다.
SIDO_LABEL_ALIASES: Mapping[str, tuple[str, ...]] = {
    "서울": ("서울특별시",),
    "부산": ("부산광역시",),
    "대구": ("대구광역시",),
    "인천": ("인천광역시",),
    "광주": ("광주광역시",),
    "대전": ("대전광역시",),
    "울산": ("울산광역시",),
    "세종": ("세종특별자치시",),
    "경기": ("경기도",),
    "강원": ("강원특별자치도", "강원도"),
    "충북": ("충청북도",),
    "충남": ("충청남도",),
    "전북": ("전북특별자치도", "전라북도"),
    "전남": ("전라남도",),
    "경북": ("경상북도",),
    "경남": ("경상남도",),
    "제주": ("제주특별자치도",),
}


def official_sido_labels(abbreviation: str) -> tuple[str, ...]:
    """축약명이 가리키는 행안부 정식명들을 돌려준다. 표에 없으면 빈 tuple이다.

    표에 없는 이름을 추측으로 만들지 않는 것이 이 함수의 전부다. 빈 tuple은 "모른다"이고, 그 코드는
    미매핑으로 남아 coverage가 센다.
    """
    return SIDO_LABEL_ALIASES.get(abbreviation, ())
