/** @module 책임: 한 회차 명단의 행 수 상한과, 그 상한 초과를 한 조회에서 감지하기 위한 읽기 행 수를 소유한다. */

/**
 * 한 회차 명단이 가질 수 있는 행 수 상한이다. 원천 명단 계약(ingestion `bid-roster`의 `submissions`)과
 * 공개 명단 계약(`rows`)이 같은 상한을 쓰며 이 값은 그 둘의 서버 쪽 대응이다. 회차별 상한이라 요청 크기와
 * 무관하고, 넘긴 명단은 잘라서 성공시키지 않고 무결성 결함으로 격리한다.
 */
export const MAX_ROSTER_ROWS = 2048;

/**
 * 명단 SQL이 읽는 행 수다. 상한보다 한 행을 더 읽어야 "정확히 상한"과 "상한 초과"가 같은 조회에서
 * 갈린다. 상한만큼만 읽으면 초과한 명단이 상한 크기의 정상 명단으로 보여 조용히 성공한다.
 */
export const ROSTER_QUERY_ROW_LIMIT = MAX_ROSTER_ROWS + 1;
